import assert from 'node:assert/strict';
import {test} from 'node:test';
import {readFile} from 'node:fs/promises';
import {GalacticTrailHistory,MAX_GALACTIC_TRAIL_SAMPLES} from '../src/renderer/galactic-trails.js';
import {SolarRenderer} from '../src/renderer/renderer.js';
import {DAY} from '../src/renderer/math.js';

const t0=Date.UTC(2026,10,20);
const sun={id:'sun',type:'star'};
const earth={id:'earth',type:'planet',parentId:'sun',periodDays:365.25};

const startHistory=()=>{
  const h=new GalacticTrailHistory();
  assert.equal(h.record(sun,t0,[0,0,0]).length,0);
  assert.equal(h.record(earth,t0,[6,0,1]).length,0);
  return h;
};

test('v103: no line is generated by real elapsed time, 2.4 second reveal or disabled animation',()=>{
  const h=startHistory();
  // Wall-clock time has advanced; the *simulated* time has not.
  for(let i=0;i<100;i++){
    assert.equal(h.record(sun,t0,[0,0,0]).length,0);
    assert.equal(h.record(earth,t0,[6,0,1]).length,0);
  }
  assert.equal(h.trails.get('sun').samples.length,1);
  assert.equal(h.trails.get('earth').samples.length,1);
});

test('v103: each object extends only after its simulated clock advances',()=>{
  const h=startHistory();
  const sunPath=h.record(sun,t0+DAY,[0,0,0]);
  assert.equal(sunPath.length,6);
  assert.ok(sunPath[1]<0);
  assert.equal(sunPath[4],0,'the Sun is still the 3D origin');
  assert.equal(h.record(earth,t0,[6,0,1]).length,0,
    'Earth does not obtain history until its own next simulated position');
  const earthPath=h.record(earth,t0+DAY,[6.02,.3,.98]);
  assert.equal(earthPath.length,6);
  assert.ok(earthPath[1]<0);
  assert.deepEqual([...earthPath.slice(-3)],[Math.fround(6.02),Math.fround(.3),Math.fround(.98)]);
});

test('v103: leaving and re-entering galactic mode clears both Sun and planet trails',()=>{
  const r=Object.create(SolarRenderer.prototype);
  r.planetId=null;r.selectedId='earth';r.simTime=t0;
  r.settings={orbits:false,galacticMotion:false,row:false,scaleOrbits:false};
  r.bodies=[];r.positions=new Map([['sun',[0,0,0]],['earth',[6,0,1]]]);
  r.calcPositions=()=>{};r.cinema=null;r._sceneRevision=0;
  r.start(t0,'earth',r.settings);
  r.settings.galacticMotion=true;r.settings.orbits=true;
  r.start(t0,'earth',r.settings);
  assert.equal(r._galacticTrailModeActive,true);
  r._galacticTrails=startHistory();
  r._galacticTrails.record(sun,t0+DAY,[0,0,0]);
  assert.equal(r._galacticTrails.record(earth,t0+DAY,[6,0.5,1]).length,6);
  r.settings.galacticMotion=false;
  r.start(t0+DAY,'earth',r.settings);
  assert.equal(r._galacticTrailModeActive,false);
  assert.equal(r._galacticTrails.trails.size,0);
  r.settings.galacticMotion=true;
  r.start(t0+DAY,'earth',r.settings);
  assert.equal(r._galacticTrailModeActive,true);
  assert.equal(r._galacticTrails.record(sun,t0+DAY,[0,0,0]).length,0);
  assert.equal(r._galacticTrails.record(earth,t0+DAY,[6,0.5,1]).length,0);
});

test('v103: pausing preserves the recorded line; resetting it starts at zero again',()=>{
  const h=startHistory();
  const a=Float32Array.from(h.record(sun,t0+DAY*40,[0,0,0]));
  const b=Float32Array.from(h.record(sun,t0+DAY*40,[0,0,0]));
  assert.deepEqual([...b],[...a]);
  h.clear();
  assert.equal(h.record(sun,t0+DAY*40,[0,0,0]).length,0);
});

test('v103: recorded paths are bounded in age and sample count, even at high simulation speeds',()=>{
  const h=new GalacticTrailHistory(20);
  const start=t0-365.25*DAY*20;
  for(let i=0;i<2000;i++)h.record(sun,start+i*30*DAY,[0,0,0]);
  const trail=h.trails.get('sun');
  assert.ok(trail.samples.length<=20);
  assert.ok(trail.samples.every(s=>s.time>=h.time-(365.25*18)*DAY));
  const points=h.record(sun,h.time+DAY,[0,0,0]);
  assert.ok(points.length<=21*3);
  assert.ok(MAX_GALACTIC_TRAIL_SAMPLES>=20);
});

test('v103: a backwards time jump and changed scene scale never connect old and new histories',()=>{
  const h=startHistory();
  const later=t0+40*DAY;
  assert.equal(h.record(earth,later,[6,1,0]).length,6);
  assert.equal(h.record(sun,later,[0,0,0]).length,6);
  const backward=t0-5*DAY;
  assert.equal(h.record(sun,backward,[0,0,0]).length,0,'rewind starts with zero length');
  assert.equal(h.trails.size,1,'other bodies were discarded by the rewind');
  assert.equal(h.record(earth,backward,[5.8,0,1]).length,0);
  assert.equal(h.record(earth,backward+DAY,[5.7,0,1]).length,6);
  assert.equal(h.record(earth,backward+2*DAY,[9,0,1],'physical').length,0,
    'changing the orbital scale clears the history');
  assert.equal(h.trails.size,1,'old-scale solar samples are all discarded');
});

